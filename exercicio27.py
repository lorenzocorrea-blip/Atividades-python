n = int(input("Digite um número: ")) # lê o número digitado pelo usuário
if 1 <= n and n <= 100: # se 1 for menor ou igual a n e n for menor ou igual a 100, ele está entre 1 e 100. senão ele não está entre 1 e 100.
    print("O número está entre 1 e 100.")
else:
    print("O número não está entre 1 e 100.")